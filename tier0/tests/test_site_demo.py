"""The site's simulated-Slack demo (site/demo.html and its run log, site/demo.json).

Both files are generated by `python -m tier0.site_demo --out site` (or `make site-demo`), which
plays one recorded run of the real agent on the mocks back (site/demo-recorded-run.json; the
owner's ruling 10). These tests fail if either file drifts from a new replay, if the replay
calls a model or asks for a call the recording doesn't hold, if the page doesn't state the
recording's models and date, if the guide shown isn't the recorded pick, if the message is not
a tuning template word for word, or if the page loses its "Simulated Slack, fake data" label or
its link from the Tier0 case study.
"""

import copy
import html
import json
import re
from datetime import UTC, datetime
from functools import cache
from pathlib import Path
from typing import Any

import pytest

from meridian_dataset.month import SEALED_SETS, SPENT_SETS, TUNING_MONTH, load_templates
from tier0 import site_demo
from tier0.evals.month import SEALED_PLANS
from tier0.evals.setups import HAIKU, SONNET
from tier0.knowledge.prompts import PICKER_MODES, sha256
from tier0.models import ModelRequest, ModelResponse
from tier0.models.claude import ClaudeModel
from tier0.models.pricing import tokens_usd
from tier0.models.spend import ITEM_ENV, SpendCapReached

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"


@cache
def _made() -> dict[str, str]:
    return site_demo.files()


def _published() -> dict[str, Any]:
    return json.loads((SITE / "demo.json").read_text())


def _recording() -> dict[str, Any]:
    return json.loads((SITE / site_demo.RECORDING).read_text())


def _page() -> str:
    return (SITE / "demo.html").read_text()


def _call(task: str) -> dict[str, Any]:
    (call,) = [c for c in _recording()["calls"] if c["request"]["task"] == task]
    return call


def test_the_files_are_what_the_generator_makes() -> None:
    made = _made()
    assert sorted(made) == sorted(site_demo.FILES)
    for name, text in made.items():
        assert (SITE / name).read_text() == text, (
            f"site/{name} drifted from its generator: run make site-demo"
        )


def test_the_page_is_built_from_the_published_run_log_alone() -> None:
    assert site_demo.render(_published()) == _page()


def test_the_message_is_a_tuning_template_word_for_word() -> None:
    run = _published()
    source = run["source"]
    assert source["template_set"] == TUNING_MONTH == "tuning_month"
    assert source["template_set"] not in SEALED_SETS
    assert source["template_set"] not in SPENT_SETS
    assert not source["template_set"].startswith("held_out")
    (template,) = [t for t in load_templates(TUNING_MONTH) if t.id == source["template"]]
    assert run["message"]["text"] == template.text
    assert source["expected_guide"] == template.expected_guide
    assert html.escape(template.text) in _page()
    recorded = _recording()["source"]
    assert recorded == {k: source[k] for k in ("template_set", "template", "world_seed")}


# --- the recorded run ----------------------------------------------------------------------


def test_the_recording_is_one_complete_run_of_the_3e_arm_under_its_limit() -> None:
    rec = _recording()
    assert rec["complete"] is True and "error" not in rec
    assert rec["arm"] == "haiku-3d2" == site_demo.ARM.name
    assert rec["budget_item"] == site_demo.BUDGET_ITEM == "tier0-3e"
    assert rec["prompt_cache"] is False
    assert datetime.fromisoformat(rec["recorded_at"]).date().isoformat() == rec["recorded_on"]
    # Triage on haiku-3d2's model and prompt, the picker KS6A-H on Sonnet: milestone 3e's
    # frozen prompt, the same bytes as the blind months' plan pinned by SHA-256.
    assert [(c["request"]["task"], c["model_asked"], c["prompt"]) for c in rec["calls"]] == [
        ("triage", HAIKU, "HT9"),
        ("guide_pick", SONNET, "KS6A-H"),
    ]
    assert rec["arm_prompts"] == site_demo.prompts()
    assert rec["arm_prompts"]["triage"]["version"] == site_demo.ARM.triage_prompt
    picker = rec["arm_prompts"]["guide_pick"]
    assert picker["sha256"] == sha256("KS6A-H")
    assert picker["sha256"] == SEALED_PLANS["held_out_month2"].picker_prompt_sha256
    assert "KS6A-H" not in PICKER_MODES  # one call, like KS5: GuidePicker's own flow
    assert _call("triage")["request"]["system_sha256"] == rec["arm_prompts"]["triage"]["sha256"]
    # The cost is the replies' token counts at the price table's rates, under the limit.
    for call in rec["calls"]:
        r = call["reply"]
        cost, known = tokens_usd(
            r["model"],
            r["input_tokens"],
            r["output_tokens"],
            cache_write_tokens=r["cache_write_tokens"],
            cache_read_tokens=r["cache_read_tokens"],
        )
        assert known and call["cost_usd"] == round(cost, 8)
        assert r["finish_reason"] == "stop" and r["response_id"]
    assert rec["cost_usd"] == round(sum(c["cost_usd"] for c in rec["calls"]), 8)
    assert 0 < rec["cost_usd"] < site_demo.RECORD_LIMIT_USD == 0.05


def test_the_page_states_the_recordings_models_and_date() -> None:
    rec, run, page = _recording(), _published(), _page()
    triage, pick = _call("triage")["reply"]["model"], _call("guide_pick")["reply"]["model"]
    assert run["models"] == {
        "recorded_on": rec["recorded_on"],
        "recording": site_demo.RECORDING,
        "triage": {"model": triage, "prompt": "HT9"},
        "guide_pick": {"model": pick, "prompt": "KS6A-H"},
    }
    assert (site_demo.model_name(triage), site_demo.model_name(pick)) == (
        "Claude Haiku 5.5",
        "Claude Sonnet 5.5",
    )
    line = (
        f"Recorded once on {rec['recorded_on']} with Claude Haiku 5.5 (triage) and Claude "
        "Sonnet 5.5 (guide picker); the page replays that run, it doesn't call a model."
    )
    assert site_demo.recorded_line(run["models"]) == line
    hero = page.index('<div class="hero">')
    assert hero < page.index(f"<strong>{line}</strong>") < page.index('id="replay"')
    assert f'href="{site_demo.RECORDING}"' in page
    for model_id in (triage, pick):
        assert f"<dd>{model_id}</dd>" in page
    assert "<code>HT9</code>" in page and "<code>KS6A-H</code>" in page


def test_the_recordings_guide_and_label_are_the_ones_shown() -> None:
    run, page = _published(), _page()
    picked = json.loads(_call("guide_pick")["reply"]["text"])
    assert picked == {"request_type": run["pick"]["request_type"], "guide": run["pick"]["guide"]}
    assert picked["guide"] == run["guide"]["id"] == run["source"]["expected_guide"]
    assert run["pick"]["version"] == "KS6A-H"
    assert f"<dd>{picked['guide']}</dd>" in page
    assert html.escape(run["guide"]["title"]) in page
    assert run["guide"]["title"] in run["reply"]["text"]
    label = json.loads(_call("triage")["reply"]["text"])
    assert label == run["triage"] == {"category": "other"}


def test_the_replay_calls_no_model(monkeypatch: pytest.MonkeyPatch) -> None:
    """The network is already blocked in tests (conftest); a Claude call fails loudly too."""

    def no_call(self: ClaudeModel, request: ModelRequest) -> ModelResponse:
        raise AssertionError("the replay called Claude")

    monkeypatch.setattr(ClaudeModel, "complete", no_call)
    monkeypatch.setattr("tier0.models.claude.read_api_key", lambda *a, **k: pytest.fail("key"))
    assert site_demo.replay(_recording()) == _published()


@pytest.mark.parametrize(
    ("task", "field"),
    [
        ("triage", "system_sha256"),
        ("triage", "user_sha256"),
        ("guide_pick", "system_sha256"),
        ("guide_pick", "schema_sha256"),
        ("guide_pick", "max_tokens"),
    ],
)
def test_a_call_the_recording_doesnt_hold_stops_the_replay(task: str, field: str) -> None:
    rec = copy.deepcopy(_recording())
    (call,) = [c for c in rec["calls"] if c["request"]["task"] == task]
    call["request"][field] = 1 if field == "max_tokens" else "0" * 64
    with pytest.raises(site_demo.ReplayMismatch, match=field):
        site_demo.replay(rec)


def test_a_recording_with_a_call_left_over_or_missing_is_refused() -> None:
    rec = copy.deepcopy(_recording())
    rec["calls"].append(copy.deepcopy(rec["calls"][-1]))
    with pytest.raises(site_demo.ReplayMismatch, match="fewer calls"):
        site_demo.replay(rec)
    rec["calls"] = rec["calls"][:1]
    with pytest.raises(site_demo.ReplayMismatch, match="no more"):
        site_demo.replay(rec)


def test_an_incomplete_recording_is_refused(tmp_path: Path) -> None:
    rec = copy.deepcopy(_recording())
    rec["complete"] = False
    rec["error"] = "RuntimeError: the run went another way"
    path = tmp_path / site_demo.RECORDING
    path.write_text(json.dumps(rec))
    with pytest.raises(site_demo.ReplayMismatch, match="not a complete run"):
        site_demo.load_recording(path)


# --- the recorder, offline ---------------------------------------------------------------


class _Fake:
    """Stands in for Claude in the recorder's own tests: the recorded run's replies."""

    provider = "fake"
    temperature: float | None = None
    seed: int | None = None
    supports_seed = False

    def __init__(self, model: str) -> None:
        self.model = model
        self.calls = 0

    def describe(self) -> dict[str, str]:
        return {}

    def complete(self, request: ModelRequest) -> ModelResponse:
        self.calls += 1
        text = _call(request.task)["reply"]["text"]
        return ModelResponse(text, self.model, 1000, 10, "stop", f"fake-{request.task}")


def test_the_recorder_saves_a_run_the_page_can_be_built_from(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv(ITEM_ENV, "tier0-3e")
    fakes: list[_Fake] = []

    def make(model: str) -> _Fake:
        fakes.append(_Fake(model))
        return fakes[-1]

    when = datetime(2026, 11, 19, 21, 0, tzinfo=UTC)
    rec = site_demo.record_once(tmp_path, make_model=make, clock=lambda: when)
    assert [f.calls for f in fakes] == [1, 1]
    assert json.loads((tmp_path / site_demo.RECORDING).read_text()) == rec
    assert (rec["recorded_on"], rec["complete"]) == ("2026-11-19", True)
    assert [c["request"] for c in rec["calls"]] == [c["request"] for c in _recording()["calls"]]
    made = site_demo.files(site=tmp_path)
    assert "Recorded once on 2026-11-19 with Claude Haiku 5.5 (triage)" in made["demo.html"]
    # Only the recording's own facts differ from the published page's run log.
    run = json.loads(made["demo.json"])
    assert {k: v for k, v in run.items() if k != "models"} == {
        k: v for k, v in _published().items() if k != "models"
    }


def test_the_recorder_refuses_before_any_call(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    def make(model: str) -> _Fake:
        raise AssertionError("a model was built")

    monkeypatch.setenv(ITEM_ENV, "tier0-3d")
    with pytest.raises(SpendCapReached, match="tier0-3e"):
        site_demo.record_once(tmp_path, make_model=make)
    monkeypatch.setenv(ITEM_ENV, "tier0-3e")
    (tmp_path / site_demo.RECORDING).write_text("{}")
    with pytest.raises(FileExistsError, match="recorded once"):
        site_demo.record_once(tmp_path, make_model=make)
    monkeypatch.setattr(site_demo, "RECORD_LIMIT_USD", 0.001)
    with pytest.raises(SpendCapReached, match="over its limit"):
        site_demo.record_once(tmp_path, make_model=make, replace=True)
    assert (tmp_path / site_demo.RECORDING).read_text() == "{}"


def test_the_estimate_is_far_under_the_limit() -> None:
    rows = site_demo.estimate()
    assert [(r["task"], r["model"]) for r in rows] == [("triage", HAIKU), ("guide_pick", SONNET)]
    assert sum(r["worst_case_usd"] for r in rows) < site_demo.RECORD_LIMIT_USD / 2
    assert sum(r["expected_usd"] for r in rows) < 0.01


