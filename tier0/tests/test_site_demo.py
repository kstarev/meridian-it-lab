"""The site's simulated-Slack demo (site/demo.html and its run log, site/demo.json).

Both files are generated by `python -m tier0.site_demo --out site` (or `make site-demo`) from one
run of the real agent on the mocks. These tests fail if either file drifts from a new run, if
the message is not a tuning template word for word, if a paid or real model is named, or if
the page loses its "Simulated Slack, fake data" label or its link from the Tier0 case study.
"""

import html
import json
import re
from functools import cache
from pathlib import Path
from typing import Any

from meridian_dataset.month import SEALED_SETS, SPENT_SETS, TUNING_MONTH, load_templates
from tier0 import site_demo

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "site"


@cache
def _made() -> dict[str, str]:
    return site_demo.files()


def _published() -> dict[str, Any]:
    return json.loads((SITE / "demo.json").read_text())


def _page() -> str:
    return (SITE / "demo.html").read_text()


def test_the_files_are_what_the_generator_makes() -> None:
    made = _made()
    assert sorted(made) == sorted(site_demo.FILES)
    for name, text in made.items():
        assert (SITE / name).read_text() == text, (
            f"site/{name} drifted from its generator: run make site-demo"
        )


def test_the_page_is_built_from_the_published_run_log_alone() -> None:
    assert site_demo.render(_published()) == _page()


def test_the_message_is_a_tuning_template_word_for_word() -> None:
    run = _published()
    source = run["source"]
    assert source["template_set"] == TUNING_MONTH == "tuning_month"
    assert source["template_set"] not in SEALED_SETS
    assert source["template_set"] not in SPENT_SETS
    assert not source["template_set"].startswith("held_out")
    (template,) = [t for t in load_templates(TUNING_MONTH) if t.id == source["template"]]
    assert run["message"]["text"] == template.text
    assert source["expected_guide"] == template.expected_guide
    assert html.escape(template.text) in _page()


def test_only_the_offline_stub_and_the_scripted_fake_ran() -> None:
    run = _published()
    assert run["models"] == {
        "triage": "tier0.stub/tier0-stub-1",
        "guide_pick": "stub/scripted",
    }
    assert not re.search(r"claude-|ollama", json.dumps(run["models"]))


def test_the_story_is_the_one_the_notes_describe() -> None:
    run = _published()
    assert run["triage"] == {"category": "other"}
    assert run["pick"]["guide"] == run["guide"]["id"] == run["source"]["expected_guide"]
    assert run["guide"]["approved"] and not run["guide"]["flagged"]
    assert run["tokens_issued"] == run["tool_calls"] == 0
    assert run["ticket"]["state_after_reply"] == "Awaiting reply"
    assert run["ticket"]["state_at_close"] == "Done"
    # The reply is code's: the AI disclosure, then the guide's title and link.
    assert "AI assistant" in run["reply"]["text"]
    assert run["guide"]["title"] in run["reply"]["text"]


def test_the_page_is_labelled_and_says_what_ran() -> None:
    page = _page()
    label = "Simulated Slack, fake data"
    hero = page.index('<div class="hero">')
    assert page.index(label, hero) < page.index("<h1>")
    # Every Slack-style message carries the label too.
    assert page.count('class="slack-bar"') == page.count(label) - 1 == 3
    assert "no AI model made the pick" in page
    assert "offline stub" in page


def test_the_page_shows_no_result_numbers() -> None:
    assert "%" not in re.sub(r"<head>.*?</head>", "", _page(), flags=re.S)


def test_the_tier0_case_study_links_to_the_demo() -> None:
    tier0 = (SITE / "tier0.html").read_text()
    assert 'href="demo.html"' in tier0
    assert 'href="tier0.html"' in _page()
