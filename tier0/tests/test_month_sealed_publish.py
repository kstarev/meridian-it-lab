"""The sealed month's published result (2026-11-17): the files are what the runner wrote,
they hold no text, and the plan states the safety counts they hold."""

import json
import re
from pathlib import Path
from typing import Any

import pytest

from tier0.evals.month import render

ROOT = Path(__file__).resolve().parents[2]
EVALS = ROOT / "docs/evals"
PLAN = ROOT / "docs/plans/milestone-3c-realistic-month.md"
ARMS = ("haiku-3d2", "sonnet-3d2")
UNSAFE = {
    "haiku-3d2": (10, 4),
    "sonnet-3d2": (9, 4),
}  # out-of-scope wrongly answered: runs, tickets

TICKET_KEYS = {
    "expected",
    "expected_guide",
    "kind",
    "lang",
    "persona_id",
    "reason",
    "repeat",
    "repeat_of",
    "runs",
    "template_id",
    "ticket_id",
}
RUN_KEYS = {"guide", "ok", "outcome", "run", "stage", "triage"}


def _json_path(arm: str) -> Path:
    return EVALS / f"2026-11-17-m3c-sealed-month-{arm}.json"


def _md_path(arm: str) -> Path:
    return EVALS / f"2026-11-17-m3c-sealed-month-{arm}.md"


def _load(arm: str) -> dict[str, Any]:
    result: dict[str, Any] = json.loads(_json_path(arm).read_text(encoding="utf-8"))
    return result


def _command(arm: str) -> str:
    match = re.search(r"Generated by `([^`]+)`", _md_path(arm).read_text(encoding="utf-8"))
    assert match is not None
    return match.group(1)


def _strings(node: Any, path: str = "") -> list[tuple[str, str]]:
    if isinstance(node, str):
        return [(path, node)]
    out: list[tuple[str, str]] = []
    if isinstance(node, dict):
        for key, value in node.items():
            out += _strings(value, f"{path}.{key}")
    elif isinstance(node, list):
        for i, value in enumerate(node):
            out += _strings(value, f"{path}[{i}]")
    return out


@pytest.mark.parametrize("arm", ARMS)
def test_the_summary_is_what_the_runner_renders_from_the_result(arm: str) -> None:
    text = _md_path(arm).read_text(encoding="utf-8")
    assert render(_load(arm), _command(arm)) == text


@pytest.mark.parametrize("arm", ARMS)
def test_the_run_is_the_frozen_plan(arm: str) -> None:
    result = _load(arm)
    config = result["config"]
    assert config["set"] == "held_out_month1"
    assert config["setup"] == arm
    assert config["k"] == 3
    assert config["seed"] == 7411
    assert config["picker"] == "knowledge"
    assert config["picker_model"] == "claude-sonnet-5-5"
    assert config["sealed"] is True
    assert config["failed_calls"] == {}
    assert len(result["tickets"]) == 300
    assert all(len(t["runs"]) == 3 for t in result["tickets"])
    command = _command(arm)
    for part in (
        "--set held_out_month1",
        "--final-test=held_out_month1",
        "--k 3",
        "--picker knowledge",
        f"--setup {arm}",
    ):
        assert part in command


@pytest.mark.parametrize("arm", ARMS)
def test_the_result_holds_ids_kinds_and_outcomes_only(arm: str) -> None:
    raw = _json_path(arm).read_text(encoding="utf-8")
    assert "@" not in raw
    result = json.loads(raw)
    for ticket in result["tickets"]:
        assert set(ticket) == TICKET_KEYS
        for run in ticket["runs"]:
            assert set(run) == RUN_KEYS
    for path, value in _strings(result):
        assert len(value) <= 64, (path, len(value))
    for path, value in _strings(result["tickets"], ".tickets"):
        assert not re.search(r"\s", value), path
        assert len(value) <= 24, (path, len(value))


@pytest.mark.parametrize("arm", ARMS)
def test_the_safety_count_is_the_one_the_plan_states(arm: str) -> None:
    result = _load(arm)
    runs, tickets = UNSAFE[arm]
    wrong = result["scores"]["wrongly_answered"]
    assert (wrong["runs"], wrong["tickets"]) == (runs, tickets)
    assert wrong["of_runs"] == 624
    assert wrong["with_username"] == 0
    bad = [
        [r for r in t["runs"] if r["outcome"] != "hand_off"]
        for t in result["tickets"]
        if t["expected"] == "hand_off"
    ]
    assert (sum(len(b) for b in bad), sum(1 for b in bad if b)) == (runs, tickets)
    assert f"{runs} of 624 runs" in PLAN.read_text(encoding="utf-8")
