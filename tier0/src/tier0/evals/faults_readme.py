"""The fault-injection table in docs/how-it-works.md, generated from the published reports:

    python -m tier0.evals.faults_readme --doc docs/how-it-works.md [--reports-dir DIR]

DIR defaults to evals next to the doc, and links are relative to the doc's folder. Runs are
numbered in PUBLISHED order (below), which the doc's text ("In run 2", ...) depends on. Each
report's "what changed" label is fixed below by file name, and a report without a label is
refused. Nothing is re-run.
"""

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from types import MappingProxyType
from typing import Any

from tier0.evals import readme_blocks
from tier0.evals.faults import COLLEAGUE_LABELS

FAULTS_START = "<!-- faults:start -->"
FAULTS_END = "<!-- faults:end -->"

_ADR_017 = (
    "decisions.md#adr-017-an-independent-own-account-only-check-and-a-code-only-mention-"
    "check-before-any-token"
)
_ADR_023 = "decisions.md#adr-023-tuning-colleague-requests-include-ones-that-name-nobody"
_ADR_024 = (
    "decisions.md#adr-024-a-code-only-role-signal-a-person-word-near-a-login-word-goes-to-a-person"
)

LABELS: Mapping[str, str] = MappingProxyType(
    {
        "2026-11-09-fault-injection": "Named colleague requests only",
        "2026-11-09-fault-injection-named-unnamed": (
            f"Adds requests that name nobody ([ADR-023]({_ADR_023}))"
        ),
        "2026-11-09-fault-injection-k-role-signal": (
            f"Check prompt version K ([ADR-017]({_ADR_017})) and the role signal "
            f"([ADR-024]({_ADR_024}))"
        ),
        "2026-11-09-fault-injection-self-description": (
            f"The role signal's self-description exception ([ADR-024]({_ADR_024}))"
        ),
    }
)
PUBLISHED = tuple(LABELS)
# The doc's intro states these once for every run, so the reports must agree on them.
SAME_SETTINGS = ("k", "rate", "fault_seed", "world_seeds", "message_pool")


def _models(data: Mapping[str, Any]) -> dict[str, Any]:
    return {m: v for m, v in data["models"].items() if not v["pipeline_check"]}


def _groups(summary: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    if "colleague" in summary:
        return [summary["colleague"]]
    return [summary[key] for key in COLLEAGUE_LABELS]


def _cell(summary: Mapping[str, Any]) -> str:
    if "colleague" in summary:
        g = summary["colleague"]
        text = f"{g['answered']} of {g['flipped_runs']}"
        return f"**{text}**" if g["answered"] > 0 else text

    def part(label: str, g: Mapping[str, Any]) -> str:
        text = f"{label} {g['answered']} of {g['flipped_runs']}"
        return f"**{text}**" if g["answered"] > 0 else text

    return "; ".join(part(label, summary[key]) for key, label in COLLEAGUE_LABELS.items())


def _exposed(models: Mapping[str, Any]) -> int:
    total = 0
    for v in models.values():
        s = v["summary"]
        total += sum(g["data_exposed_runs"] for g in _groups(s))
        total += s["outsider"]["data_exposed_runs"]
    return total


def faults_block(reports: Sequence[tuple[str, Mapping[str, Any]]], links: Sequence[str]) -> str:
    for stem, _ in reports:
        if stem not in LABELS:
            raise ValueError(f"no label for {stem}")
    names = list(_models(reports[0][1]))
    if any(set(_models(data)) != set(names) for _, data in reports):
        raise ValueError("the reports do not list the same models")
    first = reports[0][1]
    for key in SAME_SETTINGS:
        if any(data.get(key) != first.get(key) for _, data in reports):
            raise ValueError(f"the reports differ in {key}")
    header = "| Run | What changed | " + " | ".join(
        f"{m}: flipped colleague runs answered" for m in names
    )
    lines = [
        FAULTS_START,
        "",
        "Generated by `python -m tier0.evals.faults_readme` from the fault-injection reports "
        "— do not edit by hand. Tuning data, so these counts show what the checks can do, not "
        "a performance number.",
        "",
        header + " | Data exposed |",
        "| " + " | ".join(["---"] * (len(names) + 3)) + " |",
    ]
    for i, ((stem, data), link) in enumerate(zip(reports, links, strict=True), start=1):
        used = _models(data)
        cells = " | ".join(_cell(used[m]["summary"]) for m in names)
        lines.append(f"| [{i}]({link}) | {LABELS[stem]} | {cells} | {_exposed(used)} |")
    lines += ["", FAULTS_END]
    return "\n".join(lines)


def replace_faults_block(readme: str, block: str) -> str:
    return readme_blocks.replace_between(readme, block, FAULTS_START, FAULTS_END, "fault-injection")


def render(reports_dir: Path, root: Path) -> str:
    paths = [reports_dir / f"{stem}.json" for stem in PUBLISHED]
    reports = [(p.stem, json.loads(p.read_text())) for p in paths]
    links = [p.with_suffix(".md").resolve().relative_to(root.resolve()).as_posix() for p in paths]
    return faults_block(reports, links)


def main(argv: Sequence[str] | None = None) -> int:
    prog = "python -m tier0.evals.faults_readme"
    parser = argparse.ArgumentParser(prog=prog, description=__doc__)
    parser.add_argument("--doc", type=Path, required=True)
    parser.add_argument("--reports-dir", type=Path, default=None)
    args = parser.parse_args(argv)
    reports_dir = args.reports_dir or args.doc.parent / "evals"
    try:
        block = render(reports_dir, args.doc.parent)
        text = replace_faults_block(args.doc.read_text(), block)
    except (ValueError, OSError) as error:
        print(f"refused: {error}", file=sys.stderr)
        return 2
    args.doc.write_text(text)
    print(f"doc: {args.doc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
