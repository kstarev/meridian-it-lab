"""Milestone 3d part 2's dry run on its tuning world (seed 8209): the report, from saved reports.

    python -m tier0.evals.m3d2_tuning --out docs/evals/<date>-m3d2-tuning-dry-run.md

Tuning data only, and optimistic: the tuning messages were written by the tuning side, and any
new prompt version is written from these misses. Only held-out v6 measures anything. The
numbers are the final report's (`m3d2_final.arm_numbers`), on the tuning world's labels, plus
the duplicate-name group the tuning world also has. The misses are listed by ticket and code.
"""

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from meridian_dataset import TUNING_3D2_SEED, generate
from meridian_dataset.names import TUNING_3D2_POOL
from tier0.evals import m3d2_final as fin
from tier0.evals.m3d_final import Ratio, _matches

RESULTS = Path("out/3d2/dry")
LABELS = fin.LABELS / "tuning_3d2_labels.json"
DUPLICATE = ("everyday", "duplicate")


def tuning_labels() -> dict[str, tuple[str, str]]:
    """Each tuning ticket's (group, sub-group). Duplicate-name tickets are marked apart."""
    world = generate(TUNING_3D2_SEED)
    names = json.loads(LABELS.read_text(encoding="utf-8"))
    duplicates = {
        t.id for t in world.tickets if any(_matches(t.text, d) for d in TUNING_3D2_POOL.duplicate)
    }
    kept = [t for t in world.tickets if t.id not in duplicates]
    labels = fin.ticket_labels(_Tickets(kept), TUNING_3D2_POOL, names)  # type: ignore[arg-type]
    return {**labels, **dict.fromkeys(sorted(duplicates), DUPLICATE)}


class _Tickets:
    """A world with only some of its tickets, for the label mapping."""

    def __init__(self, tickets: Sequence[Any]) -> None:
        self.tickets = list(tickets)


def numbers(report: Mapping[str, Any], labels: Mapping[str, tuple[str, str]]) -> dict[str, Any]:
    dup_ids = {t for t, label in labels.items() if label == DUPLICATE}
    runs = report["runs_detail"]
    kept = {**report, "runs_detail": [r for r in runs if r["ticket"] not in dup_ids]}
    out = fin.arm_numbers(kept, {t: v for t, v in labels.items() if t not in dup_ids})
    dup_runs: dict[str, list[Mapping[str, Any]]] = {}
    for r in runs:
        if r["ticket"] in dup_ids:
            dup_runs.setdefault(r["ticket"], []).append(r)
    out["duplicate"] = Ratio(
        sum(all(r["passed"] for r in rs) for rs in dup_runs.values()), len(dup_runs)
    )
    out["misses"] = [
        (labels[r["ticket"]], r["ticket"], r["run"], r["category"], tuple(r["unsafe"]), r["action"])
        for r in runs
        if not r["passed"]
    ]
    return out


ROWS: tuple[tuple[str, Any], ...] = (
    ("Unsafe runs", lambda n: n["unsafe_runs"]),
    ("Resets prepared for a person (tickets)", lambda n: n["reset"]),
    ("Reset runs prepared as Tier C", lambda n: n["reset_prepared"]),
    (
        "Reset runs sent down the username path / caught by the signal",
        lambda n: f"{n['reset_down_username_path']} / {n['reset_caught_by_signal']}",
    ),
    ("Colleague runs stopped", lambda n: n["colleague"]["all"]["stopped"]),
    (
        "\N{EN SPACE}\N{EN SPACE}relayed, naming nobody",
        lambda n: n["colleague"]["relayed_unnamed"]["stopped"],
    ),
    (
        "\N{EN SPACE}\N{EN SPACE}reset for someone else",
        lambda n: n["colleague"]["reset_for_other"]["stopped"],
    ),
    (
        "\N{EN SPACE}\N{EN SPACE}several, with someone else's",
        lambda n: n["colleague"]["several_colleague"]["stopped"],
    ),
    ("Colleague runs caught by triage itself", lambda n: n["colleague"]["all"]["caught_by_triage"]),
    ("Repeats under the limit answered (tickets)", lambda n: n["repeat_under"]),
    ("Repeats over the limit handed off (tickets)", lambda n: n["repeat_over"]),
    ("Several-question tickets with a person (tickets)", lambda n: n["several_handed_off"]),
    ("Several-question tickets split right (tickets)", lambda n: n["several_split_right"]),
    ("Everyday requests answered (tickets)", lambda n: n["everyday"]),
    ("Duplicate-name requests answered (tickets)", lambda n: n["duplicate"]),
    ("Outsiders stopped (tickets)", lambda n: n["outsiders"]),
    ("Cost", lambda n: f"${n['cost_usd']:.4f}"),
)


def render(by_arm: Mapping[str, Mapping[str, Any]]) -> str:
    arms = [a for a in fin.ARMS if a in by_arm]
    k = {by_arm[a]["k"] for a in arms}
    lines = [
        "# Milestone 3d part 2: the dry run on the tuning world (tuning data only)",
        "",
        "Generated by `python -m tier0.evals.m3d2_tuning` from the saved reports in "
        "`out/3d2/dry/` \N{EM DASH} do not edit by hand.",
        "",
        "**Every number here is a tuning score, and optimistic.** The tuning messages were "
        "written by the tuning side, and any new prompt version is written from these misses. "
        "Only the sealed set, held-out v6, measures anything, and nothing has run on it.",
        "",
        f"Seed {TUNING_3D2_SEED}, every template once, k = {', '.join(map(str, sorted(k)))}. "
        "Ticket rows count tickets right in all runs; run rows count runs.",
        "",
        "| Measure | " + " | ".join(fin._short(a) for a in arms) + " |",
        "|---|" + "---|" * len(arms),
    ]
    for name, get in ROWS:
        lines.append(f"| {name} | " + " | ".join(str(get(by_arm[a])) for a in arms) + " |")
    lines += ["", "## Misses, by ticket", ""]
    for a in arms:
        misses = by_arm[a]["misses"]
        lines.append(f"- **{fin._short(a)}:** {len(misses)} failed runs.")
        for (group, label), ticket, run, category, unsafe, action in misses:
            code = f", unsafe {', '.join(unsafe)}" if unsafe else ""
            lines.append(
                f"  - {ticket} ({group}/{label}), run {run}: triage {category}, "
                f"action {action}{code}"
            )
    total = sum(by_arm[a]["cost_usd"] for a in arms)
    lines += ["", f"Total spent on these runs: ${total:.2f}.", ""]
    return "\n".join(lines)


def load(directory: Path = RESULTS) -> dict[str, dict[str, Any]]:
    labels = tuning_labels()
    out = {}
    for arm in fin.ARMS:
        path = directory / arm / "report.json"
        if path.exists():
            report = json.loads(path.read_text())
            if report["seed"] != TUNING_3D2_SEED or report.get("setup") != arm:
                raise ValueError(f"{path} is not {arm} on seed {TUNING_3D2_SEED}")
            out[arm] = numbers(report, labels)
    return out


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tier0.evals.m3d2_tuning", description=__doc__)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--reports", type=Path, default=RESULTS)
    args = parser.parse_args(argv)
    md = render(load(args.reports))
    if args.out is None:
        print(md)
    else:
        args.out.write_text(md)
        print(f"written: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
