"""Triage prompt selection table: python -m tier0.evals.prompt_selection --models llama3.2 ...

Scores every recorded prompt version on the same tuning messages and the chosen one on the
dev set (held-out v1). These are tuning scores, not accuracy (ADR-021). Held-out v2 is never
touched.
"""

import argparse
import json
import os
import sys
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Any

from tier0 import messages
from tier0.evals.prompt_history import CHOSEN, VERSIONS
from tier0.evals.triage_check import SCENARIOS, run_check
from tier0.models import ModelAdapter, OllamaModel
from tier0.models.base import DEFAULT_MODEL_SEED_BASE
from tier0.models.ollama import DEFAULT_OLLAMA_URL
from tier0.netguard import is_loopback_url, loopback_only

DEFAULT_K = 3
DEFAULT_TEMPERATURE = 0.5
_CHOSEN_CELL = f"{CHOSEN} (chosen): tuning, best of {len(VERSIONS)} (optimistic)"


def _counts(result: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {
        s: {"correct": v["correct"], "total": v["runs"]} for s, v in result["scenarios"].items()
    }
    out["overall"] = {"correct": result["correct"], "total": result["runs"]}
    return out


def build_selection(
    model_factories: Mapping[str, Callable[[], ModelAdapter]], *, k: int, seed_base: int
) -> dict[str, Any]:
    """Tuning pool for every version and model; the dev set too for the chosen version."""
    versions: dict[str, Any] = {}
    models: dict[str, Any] = {}
    for name in VERSIONS:
        per_model: dict[str, Any] = {}
        for model_name, factory in model_factories.items():
            tuning = run_check(factory(), "tuning", k, model_seed_base=seed_base, prompt=name)
            entry: dict[str, Any] = {"tuning": _counts(tuning)}
            if name == CHOSEN:
                dev = run_check(factory(), "held_out_v1", k, model_seed_base=seed_base, prompt=name)
                entry["dev"] = _counts(dev)
            per_model[model_name] = entry
            models.setdefault(
                model_name,
                {
                    "provider": tuning["provider"],
                    "model": tuning["model"],
                    "provenance": tuning["provenance"],
                    "temperature": tuning["temperature"],
                    "model_seeds": tuning["model_seeds"],
                    "model_seed_base": tuning["model_seed_base"],
                },
            )
        versions[name] = {"sha256": tuning["prompt_sha256"], "models": per_model}
    return {
        "k": k,
        "seed_base": seed_base,
        "chosen": CHOSEN,
        "frozen_sha256": messages.TRIAGE_SYSTEM_SHA256,
        "scenarios": list(SCENARIOS),
        "models": models,
        "versions": versions,
    }


def _cell(counts: dict[str, Any]) -> str:
    o = counts["overall"]
    parts = " / ".join(f"{counts[s]['correct']}/{counts[s]['total']}" for s in SCENARIOS)
    return f"{o['correct']}/{o['total']} ({parts})"


def _repro_lines(models: Mapping[str, Any], k: int, seed_base: int) -> list[str]:
    lines = []
    for name, m in models.items():
        p = m["provenance"]
        if "model_digest" in p:
            what = (
                f"model ID {p['model_id']} (digest {p['model_digest']}), "
                f"Ollama version {p['ollama_version']}"
            )
        else:
            what = f"model digest and Ollama version not recorded ({p.get('error', 'unavailable')})"
        temp = "none" if m["temperature"] is None else format(m["temperature"], "g")
        seeds = ", ".join(str(s) for s in m["model_seeds"]) or "none"
        lines.append(
            f"- {name}: {what}; temperature {temp}; seeds {seeds} (base {seed_base} + run)"
        )
    return lines


def render_markdown(data: Mapping[str, Any], command: str) -> str:
    k, base = data["k"], data["seed_base"]
    names = list(data["models"])
    n = len(data["versions"])
    first = next(iter(data["versions"].values()))["models"][names[0]]["tuning"]["overall"]
    messages_count = first["total"] // k
    cols = " | ".join(f"{m}: tuning score (overall, normal/duplicate/colleague)" for m in names)
    lines = [
        "# Triage prompt selection (milestone 2)",
        "",
        f"Generated by `{command}` — do not edit by hand.",
        "",
        f"Every prompt version was scored on the same {messages_count} tuning messages, "
        f"k = {k}. These are "
        f"tuning scores, not accuracy. The chosen version's score is optimistic: it was the best "
        f"of {n} on those same messages. The dev set (held-out v1) was also looked at for C, D "
        "and F, so it isn't independent either. Held-out v2 is the only performance number "
        "(ADR-021).",
        "",
        "## Reproducibility",
        "",
        *_repro_lines(data["models"], k, base),
        "",
        "## Tuning scores",
        "",
        f"| Version | Prompt SHA-256 (12) | {cols} |",
        "| --- | --- |" + " --- |" * len(names),
    ]
    for v, info in data["versions"].items():
        label = _CHOSEN_CELL if v == data["chosen"] else v
        cells = " | ".join(_cell(info["models"][m]["tuning"]) for m in names)
        lines.append(f"| {label} | {info['sha256'][:12]} | {cells} |")
    chosen = data["versions"][data["chosen"]]
    lines += [
        "",
        "## Dev-set check of the chosen version (held-out v1, diagnosis only)",
        "",
        "| Model | Dev-set check (overall, normal/duplicate/colleague) |",
        "| --- | --- |",
    ]
    for m in names:
        lines.append(f"| {m} | {_cell(chosen['models'][m]['dev'])} |")
    lines += ["", f"Frozen prompt SHA-256: `{data['frozen_sha256']}`", ""]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m tier0.evals.prompt_selection", description=__doc__
    )
    parser.add_argument("--models", nargs="+", required=True)
    parser.add_argument("--k", type=int, default=DEFAULT_K)
    parser.add_argument("--temperature", type=float, default=DEFAULT_TEMPERATURE)
    parser.add_argument("--model-seed", type=int, default=DEFAULT_MODEL_SEED_BASE, metavar="BASE")
    parser.add_argument(
        "--out", type=Path, required=True, help="the .md file; .json goes next to it"
    )
    args = parser.parse_args(argv)

    url = os.environ.get("TIER0_OLLAMA_URL", DEFAULT_OLLAMA_URL)
    if not is_loopback_url(url):
        print(f"refused: the Ollama URL must be on this machine, got {url}", file=sys.stderr)
        return 2

    def factory(name: str) -> Callable[[], ModelAdapter]:
        return lambda: OllamaModel(model=name, base_url=url, temperature=args.temperature)

    with loopback_only():
        data = build_selection(
            {m: factory(m) for m in args.models}, k=args.k, seed_base=args.model_seed
        )

    command = (
        f"python -m tier0.evals.prompt_selection --models {' '.join(args.models)} "
        f"--k {args.k} --temperature {args.temperature:g} --model-seed {args.model_seed}"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".json").write_text(json.dumps(data, indent=2) + "\n")
    args.out.write_text(render_markdown(data, command))
    print(f"report: {args.out}\njson: {args.out.with_suffix('.json')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
